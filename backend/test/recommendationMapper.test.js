'use strict';
const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs'); const path = require('node:path');
const { toPythonRequest, toPublicResponse } = require('../src/mappers/recommendationMapper');
const { validateRecommendationRequest: validate } = require('../src/validators/recommendationRequest');
const { RANKED_FIELDS, SESSION_FIELDS, TASK_FIELDS } = require('../src/mappers/fields');

const SCENARIOS = ['golden', 'empty', 'all-excluded', 'zero-time', 'top-k'].map((n) => require(`./fixtures/ml/scenario-${n}.json`));
const session = require('./fixtures/ml/scenario-golden.json').publicRequest.session;

describe('golden contract mapping (fixtures generated by the real Python engine + independent conversion)', () => {
  for (const s of SCENARIOS) {
    it(`${s.name}: public request -> exact Python payload`, () => assert.deepEqual(toPythonRequest(validate(s.publicRequest)), s.pythonRequest));
    it(`${s.name}: Python response -> expected public response (scores/ranks/categories/reasons untouched)`, () => assert.deepEqual(toPublicResponse(s.pythonResponse), s.publicResponse));
  }
  it('golden payload equals the existing Python fixture sample_request.json content', () => { const g = SCENARIOS[0]; assert.equal(g.pythonRequest.session.session_timestamp, '2026-11-16 10:00:00'); assert.equal(g.pythonRequest.tasks[0].task_id, 'T1'); });
  it('response key order and names follow the field table; mlScore is passed through exactly', () => {
    const out = toPublicResponse(SCENARIOS[0].pythonResponse); assert.deepEqual(Object.keys(out.ranked[0]), RANKED_FIELDS.map(([c]) => c));
    assert.equal(out.ranked[0].mlScore, SCENARIOS[0].pythonResponse.ranked[0].ml_score); assert.equal(typeof out.ranked[0].mlScore, 'number');
  });
});

describe('mapper semantics', () => {
  it('omitted optional fields stay omitted, null stays null', () => {
    const t = { taskId: 'A', importance: 'High', goalContribution: 'High', consequenceOfDelay: 'None', complexity: 'Simple', estimatedDurationMinutes: 10, isSplittable: false, preferredTime: 'Anytime', status: 'Pending' };
    const py = toPythonRequest({ session, tasks: [t, { ...t, taskId: 'B', dueDate: null, startDate: null }] });
    assert.equal('due_date' in py.tasks[0], false); assert.equal(py.tasks[1].due_date, null); assert.equal(py.tasks[1].start_date, null); assert.equal('top_k' in py, false);
    assert.equal(toPythonRequest({ session, tasks: [], topK: 4 }).top_k, 4);
  });
  it('only whitelisted fields are ever emitted (extra properties cannot reach Python)', () => {
    const py = toPythonRequest({ session: { ...session, bogus: 1 }, tasks: [{ taskId: 'A', due_date: 'x', evil: 1 }] }); assert.deepEqual(py.session, session && Object.fromEntries(SESSION_FIELDS.map(([c, p]) => [p, session[c]])));
    assert.deepEqual(py.tasks[0], { task_id: 'A' }); const out = toPublicResponse({ ranked: [], excluded: [{ task_id: 1, exclusion_reason: 'x', secret: 1 }], summary: { total_tasks: 1, eligible: 0, excluded: 1, returned: 0, startable_now: 0, extra: 1 } });
    assert.deepEqual(out.excluded, [{ taskId: 1, exclusionReason: 'x' }]); assert.ok(!('extra' in out.summary));
  });
  it('localTime is passed through byte-for-byte (no parsing, no timezone/DST conversion, no reformatting)', () => {
    for (const v of ['2026-11-16 10:00:00', '2026-11-16T10:00', '2026-03-08 02:30:00', '2026-10-25 01:30:00', '2028-02-29T23:59:59', '2026-12-31 23:59:59']) assert.equal(toPythonRequest({ session: { ...session, localTime: v }, tasks: [] }).session.session_timestamp, v);
  });
  it('field tables are consistent (no duplicate names, every pair complete)', () => { for (const t of [SESSION_FIELDS, TASK_FIELDS, RANKED_FIELDS]) { assert.equal(new Set(t.map((p) => p[0])).size, t.length); assert.equal(new Set(t.map((p) => p[1])).size, t.length); } });
});

describe('static guarantees', () => {
  const read = (rel) => fs.readFileSync(path.join(__dirname, '..', rel), 'utf8');
  const files = (dir) => fs.readdirSync(path.join(__dirname, '..', dir)).filter((f) => f.endsWith('.js')).map((f) => `${dir}/${f}`);
  it('mapping/validation/client code never uses Date, Intl or timezone APIs (no implicit timezone conversion)', () => {
    for (const f of [...files('src/mappers'), ...files('src/validators'), ...files('src/clients'), ...files('src/services')]) assert.doesNotMatch(read(f), /new Date|Date\.(parse|UTC|now)|Intl\.|toISOString|getTimezoneOffset|toLocale|setTimeout/, f);
  });
  it('Node contains no recommendation/scoring logic (no weights, formulas or category rules)', () => {
    for (const f of [...files('src/mappers'), ...files('src/validators'), ...files('src/clients'), ...files('src/services'), ...files('src/routes')]) assert.doesNotMatch(read(f), /WEIGHTS|0\.30\b|0\.15\b|LinearRegression|\.sort\(|Math\.(round|floor|ceil|max|min)\(.*ml/i, f);
  });
});
